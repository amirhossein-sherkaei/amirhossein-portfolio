            elseif ((Test-Path (Join-Path $ProjectRoot "bun.lockb")) -or (Test-Path (Join-Path $ProjectRoot "bun.lock"))) { $manager = "bun" }

            Write-Info ("در حال اجرای Build با {0}..." -f $manager)
            Push-Location $ProjectRoot
            try {
                switch ($manager) {
                    "pnpm" { & pnpm run build }
                    "yarn" { & yarn build }
                    "bun"  { & bun run build }
                    default { & npm run build }
                }
                $buildExit = $LASTEXITCODE
            } finally { Pop-Location }

            if ($buildExit -ne 0) {
                Write-Warn "Build موفق نشد. تغییرات و پشتیبان حفظ شده‌اند؛ به‌صورت خودکار چیزی حذف نشد. خطای Build را بررسی کن."
                Write-Warn ("پشتیبان فایل‌های اصلی: {0}" -f $report.backup)
                throw ("Build با کد {0} ناموفق بود." -f $buildExit)
            }
            Write-Success "Build با موفقیت تمام شد."
        }
    } else { Write-Warn "بررسی Build با گزینهٔ SkipBuild رد شد." }

    if ($StartDevServer) {
        Write-Info "در حال اجرای سرور توسعه..."
        $manager = "npm"
        if (Test-Path (Join-Path $ProjectRoot "pnpm-lock.yaml")) { $manager = "pnpm" }
        elseif (Test-Path (Join-Path $ProjectRoot "yarn.lock")) { $manager = "yarn" }
        elseif ((Test-Path (Join-Path $ProjectRoot "bun.lockb")) -or (Test-Path (Join-Path $ProjectRoot "bun.lock"))) { $manager = "bun" }
        $command = switch ($manager) { "pnpm" { "pnpm dev" } "yarn" { "yarn dev" } "bun" { "bun run dev" } default { "npm run dev" } }
        $quotedRoot = $ProjectRoot.Replace("'", "''")
        Start-Process -FilePath "powershell.exe" -ArgumentList @("-NoExit", "-Command", "Set-Location -LiteralPath '$quotedRoot'; $command") | Out-Null
        Start-Sleep -Seconds 3
        Start-Process "http://localhost:3000" | Out-Null
        Write-Success "پنجرهٔ سرور توسعه باز شد و مرورگر روی http://localhost:3000 قرار گرفت."
    }

    Write-Host ""
    Write-Success "SHORAKAEI SPATIAL ORBIT با موفقیت نصب شد."
    Write-Host "هیچ Git Push یا Deploy خودکاری انجام نشد." -ForegroundColor Yellow
    Write-Host "گزارش نصب: $permanentReport" -ForegroundColor Gray
    Remove-Item -LiteralPath $tempRoot -Recurse -Force -ErrorAction SilentlyContinue
}
catch {
    Write-Host ""
    Write-Fail $_.Exception.Message
    Write-Warn "اگر عملیات پس از ساخت پشتیبان متوقف شده، فایل‌های اصلی در پوشهٔ .shorakaei-backups قابل بازیابی هستند."
    if ($tempRoot -and (Test-Path -LiteralPath $tempRoot)) {
        Remove-Item -LiteralPath $tempRoot -Recurse -Force -ErrorAction SilentlyContinue
    }
    exit 1
}
