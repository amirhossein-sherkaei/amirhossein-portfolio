function Write-Info([string]$Message) { Write-Host $Message -ForegroundColor Cyan }
function Write-Success([string]$Message) { Write-Host $Message -ForegroundColor Green }
function Write-Warn([string]$Message) { Write-Host $Message -ForegroundColor Yellow }
function Write-Fail([string]$Message) { Write-Host $Message -ForegroundColor Red }

function Test-NextProject([string]$Path) {
    if ([string]::IsNullOrWhiteSpace($Path)) { return $false }
    $resolved = [System.IO.Path]::GetFullPath($Path)
    $packagePath = Join-Path $resolved "package.json"
    if (-not (Test-Path -LiteralPath $packagePath -PathType Leaf)) { return $false }
    if (-not ((Test-Path (Join-Path $resolved "src\app")) -or (Test-Path (Join-Path $resolved "app")))) { return $false }
    try {
        $pkg = Get-Content -LiteralPath $packagePath -Raw -Encoding UTF8 | ConvertFrom-Json
        return [bool](($pkg.dependencies -and $pkg.dependencies.next) -or ($pkg.devDependencies -and $pkg.devDependencies.next))
    } catch { return $false }
}

function Find-NextProject {
    $candidates = New-Object System.Collections.Generic.List[string]
    $current = (Get-Location).Path
    if (Test-NextProject $current) { $candidates.Add($current) }

    $profile = $env:USERPROFILE
    $known = @(
        (Join-Path $profile "Desktop\amirhossein-portfolio"),
        (Join-Path $profile "Desktop\shorakaei"),
        (Join-Path $profile "Documents\amirhossein-portfolio"),
        (Join-Path $profile "source\repos\amirhossein-portfolio")
    )
    foreach ($p in $known) {
        if ((Test-NextProject $p) -and -not $candidates.Contains($p)) { $candidates.Add($p) }
    }

    foreach ($base in @((Join-Path $profile "Desktop"), (Join-Path $profile "Documents"))) {
        if (Test-Path $base) {
            Get-ChildItem -LiteralPath $base -Directory -ErrorAction SilentlyContinue | Select-Object -First 40 | ForEach-Object {
                if ((Test-NextProject $_.FullName) -and -not $candidates.Contains($_.FullName)) { $candidates.Add($_.FullName) }
            }
        }
    }

    if ($candidates.Count -eq 1) { return $candidates[0] }
    if ($candidates.Count -gt 1) {
        Write-Host "چند پروژهٔ Next.js پیدا شد:" -ForegroundColor Yellow
        for ($i = 0; $i -lt $candidates.Count; $i++) { Write-Host ("[{0}] {1}" -f ($i + 1), $candidates[$i]) }
        $choice = Read-Host "شمارهٔ پوشهٔ پروژهٔ shorakaei.ir را وارد کن"
        $number = 0
        if ([int]::TryParse($choice, [ref]$number) -and $number -ge 1 -and $number -le $candidates.Count) { return $candidates[$number - 1] }
    }

    $manual = Read-Host "مسیر پوشهٔ اصلی پروژه را وارد کن (جایی که package.json قرار دارد)"
    if (Test-NextProject $manual) { return [System.IO.Path]::GetFullPath($manual) }
    throw "پروژهٔ معتبر Next.js با App Router پیدا نشد. اسکریپت هیچ تغییری در پروژه ایجاد نکرد."
}

